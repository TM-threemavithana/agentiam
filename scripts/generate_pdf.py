import os
from PIL import Image, ImageDraw, ImageFont

def generate_light_theme_slides():
    width = 1200
    height = 675
    
    # GitHub Light Theme Palette
    bg_color = (246, 248, 250)         # Light gray background
    window_border = (208, 215, 222)     # Light border
    title_bg = (243, 244, 246)         # Header background
    term_bg = (255, 255, 255)          # Terminal background (Pure White)
    text_dark = (36, 41, 47)           # Standard text (Dark gray/black)
    text_gray = (87, 96, 106)          # Dim text
    text_green = (26, 127, 55)         # Green success/prompt
    text_blue = (9, 105, 218)          # Blue info/label
    text_orange = (154, 103, 0)        # Orange warning
    text_red = (207, 34, 46)           # Red error
    
    # Load fonts
    font_path = "C:\\Windows\\Fonts\\consola.ttf"
    font_bold_path = "C:\\Windows\\Fonts\\consolab.ttf"
    
    if not os.path.exists(font_path):
        font_path = "arial.ttf"
        font_bold_path = "arial.ttf"
        
    font_normal = ImageFont.truetype(font_path, 22)
    font_bold = ImageFont.truetype(font_bold_path, 22)
    font_title = ImageFont.truetype(font_bold_path, 18)
    font_box = ImageFont.truetype(font_bold_path, 16)
    font_sub = ImageFont.truetype(font_bold_path, 12)
    
    # Helper to draw a single centered terminal window in light theme
    def create_terminal_image(title, lines):
        img = Image.new("RGB", (width, height), bg_color)
        draw = ImageDraw.Draw(img)
        
        # Centered Window Coordinates
        x, y, w, h = 80, 50, 1040, 575
        
        # Subtle Drop shadow (soft gray)
        draw.rounded_rectangle([x + 10, y + 10, x + w + 10, y + h + 10], radius=14, fill=(225, 228, 232))
        
        # Window frame
        draw.rounded_rectangle([x, y, x + w, y + h], radius=14, fill=term_bg, outline=window_border, width=2)
        
        # Header bar
        draw.rounded_rectangle([x, y, x + w, y + 50], radius=14, fill=title_bg)
        # Clear bottom round corners of header
        draw.rectangle([x, y + 30, x + w, y + 50], fill=title_bg)
        # Header bottom border line
        draw.line([x, y + 50, x + w, y + 50], fill=window_border, width=2)
        
        # Mac-style Window Controls
        colors = [(255, 95, 86), (255, 189, 46), (39, 201, 63)]
        for i, color in enumerate(colors):
            cx = x + 30 + (i * 24)
            cy = y + 25
            draw.ellipse([cx - 7, cy - 7, cx + 7, cy + 7], fill=color)
            
        # Title text
        w_title_size = draw.textlength(title, font=font_title)
        draw.text((x + (w - w_title_size) // 2, y + 14), title, fill=text_gray, font=font_title)
        
        # Render text lines
        tx = x + 35
        ty = y + 75
        line_spacing = 32
        for line in lines:
            curr_x = tx
            for text, color in line:
                draw.text((curr_x, ty), text, fill=color, font=font_normal)
                curr_x += draw.textlength(text, font=font_normal)
            ty += line_spacing
            
        return img

    os.makedirs("assets", exist_ok=True)

    # 1. Slide 1: System Architecture Slide
    def generate_architecture_slide():
        img = Image.new("RGB", (width, height), bg_color)
        draw = ImageDraw.Draw(img)
        
        x, y, w, h = 80, 50, 1040, 575
        draw.rounded_rectangle([x + 10, y + 10, x + w + 10, y + h + 10], radius=14, fill=(225, 228, 232))
        draw.rounded_rectangle([x, y, x + w, y + h], radius=14, fill=term_bg, outline=window_border, width=2)
        draw.rounded_rectangle([x, y, x + w, y + 50], radius=14, fill=title_bg)
        draw.rectangle([x, y + 30, x + w, y + 50], fill=title_bg)
        draw.line([x, y + 50, x + w, y + 50], fill=window_border, width=2)
        
        colors = [(255, 95, 86), (255, 189, 46), (39, 201, 63)]
        for i, color in enumerate(colors):
            cx = x + 30 + (i * 24)
            cy = y + 25
            draw.ellipse([cx - 7, cy - 7, cx + 7, cy + 7], fill=color)
            
        w_title_size = draw.textlength("AgentIAM Gateway System Architecture", font=font_title)
        draw.text((x + (w - w_title_size) // 2, y + 14), "AgentIAM Gateway System Architecture", fill=text_gray, font=font_title)
        
        # Load the converted SVG PNG (already generated by sharp-cli)
        svg_img = Image.open("assets/architecture_slide.png")
        
        # Scale to fit inside the terminal body area (max width 980, max height 480)
        max_w, max_h = 980, 480
        svg_w, svg_h = svg_img.size
        ratio = min(max_w / svg_w, max_h / svg_h)
        new_w = int(svg_w * ratio)
        new_h = int(svg_h * ratio)
        
        svg_scaled = svg_img.resize((new_w, new_h), Image.Resampling.LANCZOS)
        
        # Paste centered in terminal body
        paste_x = x + (w - new_w) // 2
        paste_y = y + 50 + (h - 50 - new_h) // 2
        
        if svg_scaled.mode in ('RGBA', 'LA') or (svg_scaled.mode == 'P' and 'transparency' in svg_scaled.info):
            img.paste(svg_scaled, (paste_x, paste_y), svg_scaled)
        else:
            img.paste(svg_scaled, (paste_x, paste_y))
            
        img.save("assets/architecture_slide.png", "PNG")
        print("Generated Slide 1 (Architecture from SVG)")

    generate_architecture_slide()

    # 2. Slide 2: policies.yaml
    yaml_key = (9, 105, 218)           # Blue key
    yaml_val = (207, 34, 46)           # Red string values
    yaml_comm = (87, 96, 106)          # Gray comments
    
    yaml_lines = [
        [("# yaml-language-server: $schema=./policies.schema.json", yaml_comm)],
        [("agents:", yaml_key)],
        [("  - name: ", yaml_key), ("test-agent", yaml_val)],
        [("    key: ", yaml_key), ("\"$2a$10$OAiS23oL4WZ0Db...\"", yaml_val), ("  # bcrypt password hash", yaml_comm)],
        [("    allowed_statements: ", yaml_key), ("[\"SELECT\", \"INSERT\", \"SET\"]", yaml_val)],
        [("    allowed_tables: ", yaml_key), ("[\"users\", \"orders\"]", yaml_val)],
        [("    blocked_functions: ", yaml_key), ("[\"sleep\"]", yaml_val)],
        [("    select_limit: ", yaml_key), ("20000", yaml_val)],
        [("    max_complexity: ", yaml_key), ("50", yaml_val), ("        # AST joins/aggregates scorer", yaml_comm)],
        [("    rate_limit_rpm: ", yaml_key), ("60", yaml_val)],
        [("    pool_mode: ", yaml_key), ("transaction", yaml_val), ("     # stateful connection pooling", yaml_comm)],
        [("    dialect: ", yaml_key), ("postgres", yaml_val)]
    ]
    img_yaml = create_terminal_image("policies.yaml", yaml_lines)
    img_yaml.save("assets/policies_yaml.png", "PNG")
    print("Generated Slide 2 (YAML Configuration)")

    # 3. Slide 3: Client Terminal
    client_lines = [
        [("$ ", text_gray), ("psql -h 127.0.0.1 -p 5433 -U test-agent -d production", text_dark)],
        [("Password for user test-agent: ", text_dark), ("*********", text_gray)],
        [("psql (15.0, server 15.0)", text_gray)],
        [("Type \"help\" for help.", text_gray)],
        [],
        [("production=> ", text_green), ("SELECT username, email FROM users LIMIT 1;", text_dark)],
        [(" username |       email       ", text_dark)],
        [("----------+-------------------", text_gray)],
        [(" admin    | admin@company.com", text_dark)],
        [("(1 row)", text_dark)],
        [],
        [("production=> ", text_green), ("SELECT * FROM passwords;", text_dark)],
        [("ERROR: AgentIAM Policy Violation: access to table passwords denied", text_red)],
        [("production=> ", text_green), ("█", text_green)]
    ]
    img_client = create_terminal_image("psql (test-agent@production)", client_lines)
    img_client.save("assets/client_terminal.png", "PNG")
    print("Generated Slide 3 (Client Terminal)")

    # 4. Slide 4: Gateway Logs
    gateway_lines = [
        [("2026-07-28 09:30:00 [INFO] ", text_blue), ("Starting AgentIAM Security Gateway...", text_dark)],
        [("2026-07-28 09:30:00 [INFO] ", text_blue), ("Using local LRU for AST Cache", text_dark)],
        [("2026-07-28 09:30:00 [INFO] ", text_blue), ("Upstream connection pool initialized size=50", text_dark)],
        [("2026-07-28 09:30:00 [INFO] ", text_blue), ("Registered File Audit Sink path=./audit.log", text_dark)],
        [("2026-07-28 09:30:00 [INFO] ", text_blue), ("AgentIAM Proxy Listening addr=127.0.0.1:5433", text_dark)],
        [("2026-07-28 09:30:05 [INFO] ", text_blue), ("Connection accepted remote_addr=127.0.0.1:51240", text_dark)],
        [("2026-07-28 09:30:05 [INFO] ", text_blue), ("Protocol detected protocol=postgres", text_dark)],
        [("2026-07-28 09:30:05 [INFO] ", text_blue), ("Authentication successful client_id=test-agent", text_dark)],
        [("2026-07-28 09:30:10 [INFO] ", text_blue), ("Intercepted Query client_id=test-agent", text_dark)],
        [("    query=\"SELECT username, email FROM users LIMIT 1\"", text_gray), (" status=success", text_green)],
        [("2026-07-28 09:30:15 [WARN] ", text_orange), ("Intercepted Query client_id=test-agent", text_dark)],
        [("    query=\"SELECT * FROM passwords\"", text_gray), (" status=blocked", text_red)],
        [("    error=\"access to table passwords denied\"", text_red)],
        [("█", text_dark)]
    ]
    img_gateway = create_terminal_image("agentiam-gateway-daemon", gateway_lines)
    img_gateway.save("assets/gateway_logs.png", "PNG")
    print("Generated Slide 4 (Gateway Logs)")

    # Compile PDF
    slides = [
        "assets/architecture_slide.png",
        "assets/policies_yaml.png",
        "assets/client_terminal.png",
        "assets/gateway_logs.png"
    ]
    
    images = [Image.open(s).convert("RGB") for s in slides]
    pdf_path = "assets/agentiam_slides.pdf"
    images[0].save(pdf_path, save_all=True, append_images=images[1:])
    print(f"Successfully compiled all light theme slides into: {pdf_path}")

if __name__ == "__main__":
    generate_light_theme_slides()
